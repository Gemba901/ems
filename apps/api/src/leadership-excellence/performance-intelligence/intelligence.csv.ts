import type { IntelligenceView } from './intelligence.types';

/** Quote every cell, and neutralise spreadsheet formula prefixes even after whitespace. */
export function csvCell(value: unknown): string {
  let text = value == null ? '' : String(value);
  if (/^[\s\u0000-\u001f]*[=+@-]/.test(text) && typeof value !== 'number')
    text = `'${text}`;
  return `"${text.replace(/"/g, '""')}"`;
}

